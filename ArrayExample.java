public class ArrayExample {

    public static void main (String[] args){
         int[] marks = new int[3];

         marks [0] = 90;
         marks [1] = 80;
         marks [2] = 70;

         System.out.println("First mark: " + marks[0]);

         System.out.println("Second mark: " + marks[1]);

         System.out.println("Third mark: " + marks[2]);
    }
    
}
